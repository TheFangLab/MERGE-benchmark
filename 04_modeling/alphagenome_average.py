"""
MERGE + AlphaGenome average, computed without training anything on AlphaGenome output.

Background
----------
Averaging needs the AlphaGenome column on a 0-1 scale. Fitting that scale, for
example with a one-feature logistic regression on the labels, would train a
machine-learning model on AlphaGenome output, which the AlphaGenome terms ask
users not to do ("Outputs generated by AlphaGenome should not be used for the
training of other machine learning models"). It would also add nothing: a
one-feature logistic regression is a *monotone* map, so it contributes no
ranking information of its own, and the AUROC and AUPRC of the fitted score
equal those of the raw column.

This module supplies the scale with an empirical cumulative distribution
instead:

    p_AG(x) = fraction of reference variants whose AlphaGenome score is < x
              (+ half the fraction tied with x)

No labels enter the transform, nothing is fitted, and the artefact it exports is
a table of quantile breakpoints -- a descriptive summary of published research
data rather than a trained classifier.

Feature choice
--------------
The AlphaGenome column is fixed per variant type:

    splicing   alphagenome_splicing        AlphaGenome's splice score
    noncoding  alphagenome_raw_score_max   the largest effect size across
                                           AlphaGenome's regulatory tracks

Both are raw AlphaGenome quantities rather than its quantised quantile
summaries. For noncoding variants the raw and quantile maxima rank variants
almost identically (AUROC 0.9774 for both), but the quantile column takes only
671 distinct values over 86,829 variants and its ties cost AUPRC (0.686 against
0.795 for the raw maximum); the raw maximum was chosen for that reason. Both
maxima are reported separately as comparators.

Scope
-----
Offered for splicing and non-coding variants only. On coding and non-SNV
variants the AlphaGenome columns are near chance (best AUROC 0.571 and 0.512),
so averaging them in only pulls scores toward 0.5; those two variant types
report the ensemble score alone.

Missing AlphaGenome scores
--------------------------
For evaluation, a missing AlphaGenome score (571 splicing variants; none in the
non-coding set) is replaced by the median of the training folds, in the
training and the held-out fold alike, before the percentile transform -- the
same policy as the single-feature benchmark, so the AlphaGenome component of
the average is identical to the standalone AlphaGenome score and every variant
of the fixed cohort is evaluated. The deployed tools compute the average only
for variants that have an AlphaGenome score; `alphagenome_observed` marks those
rows, and the interpretation cut-points are calibrated on them.

Outputs
-------
    05_results_alphagenome_average/{task}_alphagenome_average_oof.csv
    05_results_alphagenome_average/{task}_alphagenome_average_meta.json
    05_results_alphagenome_average/alphagenome_average_summary.csv
    05_results_alphagenome_average/alphagenome_reference_quantiles.json   (shippable)

Usage: python alphagenome_average.py
"""
import hashlib
import json
import os
from pathlib import Path

import sys

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score, average_precision_score

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from config import AGAVG, DATA, RESULTS

# Chromosome-held-out folds, identical to 04_modeling/config.py.
FOLDS = {
    1: {"3", "6", "9", "12", "16", "22", "X", "Y"},
    2: {"2", "5", "11", "14", "17", "18", "19", "20", "21"},
    3: {"1", "4", "7", "8", "10", "13", "15"},
}

# Fixed per variant type. Not chosen by AUROC -- see the module docstring.
AG_FEATURE = {
    "splicing":  "alphagenome_splicing",
    "noncoding": "alphagenome_raw_score_max",
}
DATASET = {
    "splicing":  "splicing_features.csv",
    "noncoding": "noncoding_features.csv",
}
# The no-AlphaGenome ensemble column to average with, per task.
BEST_STRATEGY_KEY = "best_strategy"

MAX_GRID = 50000   # export the exact value->percentile table below this many distinct scores
KEY = ["chr", "pos", "ref", "alt"]


def sha256_of(obj):
    return hashlib.sha256(json.dumps(obj, sort_keys=True).encode()).hexdigest()


def midrank_ecdf(values, reference):
    """Fraction of `reference` below each value, plus half the tied fraction.

    Label-free, and the mid-rank convention keeps the transform symmetric on
    ties so that a heavily tied column (many AlphaGenome scores sit at zero) is
    not pushed to one end of the scale.
    """
    ref = np.sort(np.asarray(reference, dtype=float))
    ref = ref[np.isfinite(ref)]
    v = np.asarray(values, dtype=float)
    lo = np.searchsorted(ref, v, side="left")
    hi = np.searchsorted(ref, v, side="right")
    out = (lo + hi) / (2.0 * len(ref))
    out[~np.isfinite(v)] = np.nan
    return out


def reference_table(reference, max_grid=MAX_GRID):
    """The shippable form of the same transform.

    Each distinct AlphaGenome score observed in the reference set is paired with
    the fraction of reference variants at or below it, counting ties at half
    weight. AlphaGenome's quantile columns are heavily quantised -- the
    non-coding column takes only 671 distinct values over 86,829 variants -- so
    an evenly spaced quantile grid would collapse those ties onto one end of the
    scale and shift the percentile by up to half the tie mass. Storing the
    distinct values avoids that and is smaller as well.
    """
    ref = np.asarray(reference, dtype=float)
    ref = ref[np.isfinite(ref)]
    vals, counts = np.unique(ref, return_counts=True)
    cum = np.cumsum(counts)
    mid = (cum - counts / 2.0) / len(ref)
    if len(vals) > max_grid:                    # thin, keeping the extremes
        idx = np.unique(np.linspace(0, len(vals) - 1, max_grid).astype(int))
        vals, mid = vals[idx], mid[idx]
    return vals, mid


def apply_reference_table(values, vals, mid):
    """Deployment path: interpolate onto the exported table."""
    v = np.asarray(values, dtype=float)
    out = np.interp(v, vals, mid, left=mid[0], right=mid[-1])
    out[~np.isfinite(v)] = np.nan
    return out


def load_task(task):
    df = pd.read_csv(Path(DATA) / DATASET[task], low_memory=False, dtype={"chr": str})
    df["chr"] = df["chr"].str.replace("chr", "", regex=False)
    df["fold"] = -1
    for k, chroms in FOLDS.items():
        df.loc[df["chr"].isin(chroms), "fold"] = k
    return df[df["fold"] != -1].reset_index(drop=True)


def metrics(y, p):
    ok = np.isfinite(p)
    return (float(roc_auc_score(y[ok], p[ok])),
            float(average_precision_score(y[ok], p[ok])), int(ok.sum()))


def fold_metrics(y, p, folds):
    rows = []
    for k in sorted(set(folds)):
        sel = (folds == k) & np.isfinite(p)
        if len(np.unique(y[sel])) < 2:
            continue
        rows.append((roc_auc_score(y[sel], p[sel]),
                     average_precision_score(y[sel], p[sel])))
    a = np.array(rows)
    # sample SD over the outer folds (divisor k - 1), as everywhere else
    return (float(a[:, 0].mean()), float(a[:, 0].std(ddof=1)),
            float(a[:, 1].mean()), float(a[:, 1].std(ddof=1)))


def run():
    outdir = Path(AGAVG)
    outdir.mkdir(exist_ok=True)
    noag_dir = Path(RESULTS)

    summary_rows = []
    reference_export = {"convention": "midrank empirical CDF of the AlphaGenome column "
                                      "over the benchmark variants for that variant type",
                        "labels_used": False,
                        "form": "distinct reference scores paired with their mid-rank percentile",
                        "tasks": {}}

    for task, feat in AG_FEATURE.items():
        df = load_task(task)
        meta_noag = json.loads((noag_dir / f"{task}_meta.json").read_text())
        strat = meta_noag[BEST_STRATEGY_KEY]
        oof = pd.read_csv(noag_dir / f"{task}_merge_oof.csv", dtype={"chr": str})
        oof["chr"] = oof["chr"].str.replace("chr", "", regex=False)

        m = oof[KEY + ["label", strat]].merge(df[KEY + [feat, "fold"]], on=KEY, how="left")
        m = m.drop_duplicates(KEY).reset_index(drop=True)
        assert len(m) == len(oof), f"{task}: join changed the row count"
        y = m["label"].values.astype(int)
        ens = m[strat].values.astype(float)
        raw = m[feat].values.astype(float)
        folds = m["fold"].values

        # --- out-of-fold component: missing scores take the training-fold
        # median, and the reference distribution is the (imputed) training
        # folds only, so the held-out fold contributes nothing to its own scale.
        observed = np.isfinite(raw)
        comp = np.full(len(m), np.nan)
        for k in sorted(set(folds)):
            te = folds == k
            med = float(np.nanmedian(raw[~te]))
            comp[te] = midrank_ecdf(np.where(observed[te], raw[te], med),
                                    np.where(observed[~te], raw[~te], med))

        avg = 0.5 * ens + 0.5 * comp

        # --- exported grid, fitted on every row (deployment artefact)
        vals_ref, mid_ref = reference_table(raw)
        comp_deployed = apply_reference_table(raw, vals_ref, mid_ref)
        max_dev = float(np.nanmax(np.abs(comp_deployed - midrank_ecdf(raw, raw))))

        au_a, ausd_a, ap_a, apsd_a = fold_metrics(y, avg, folds)
        au_e, ausd_e, ap_e, apsd_e = fold_metrics(y, ens, folds)
        au_c, ausd_c, ap_c, apsd_c = fold_metrics(y, comp, folds)

        pd.DataFrame({
            "chr": m["chr"], "pos": m["pos"], "ref": m["ref"], "alt": m["alt"],
            "label": y, "fold": folds,
            "merge_alphagenome_average": avg,
            "merge_no_alphagenome": ens,
            "alphagenome_component": comp,
            "alphagenome_raw": raw,
            "alphagenome_observed": observed.astype(int),
            "alphagenome_feature": feat,
        }).to_csv(outdir / f"{task}_alphagenome_average_oof.csv", index=False)

        meta = {
            "task": task,
            "offered": True,
            "dataset": f"03_datasets/{DATASET[task]}",
            "n": int(len(m)),
            "n_alphagenome_present": int(observed.sum()),
            "positive_rate": float(y.mean()),
            "display_name": "MERGE + AlphaGenome average",
            "field_name": "merge_alphagenome_average",
            "formula": "0.5 * P(MERGE without AlphaGenome) + 0.5 * ECDF percentile of the "
                       "selected AlphaGenome column",
            "weighting": "fixed 1:1, not fitted",
            "alphagenome_feature": feat,
            "feature_selection": "fixed per variant type",
            "component_transform": "training-fold median imputation, then mid-rank "
                                   "empirical CDF against the training-fold AlphaGenome "
                                   "values; no labels, no fitted model",
            "ensemble_strategy": strat,
            "missing_policy": "evaluation: a missing AlphaGenome score takes the "
                              "training-fold median before the percentile transform, so "
                              "every variant is scored; deployment: the average is "
                              "computed only where AlphaGenome has a score "
                              "(alphagenome_observed = 1)",
            "exported_table_max_abs_deviation": max_dev,
        }
        (outdir / f"{task}_alphagenome_average_meta.json").write_text(json.dumps(meta, indent=2))

        common = (f"all {len(m):,} variants; {int((~observed).sum()):,} missing "
                  f"AlphaGenome scores imputed with the training-fold median")
        for label, (au, ausd, ap, apsd) in [
                ("MERGE + AlphaGenome average", (au_a, ausd_a, ap_a, apsd_a)),
                ("MERGE without AlphaGenome", (au_e, ausd_e, ap_e, apsd_e)),
                ("AlphaGenome component alone", (au_c, ausd_c, ap_c, apsd_c))]:
            summary_rows.append({
                "task": task, "offered": "yes", "predictor": label,
                "selected_alphagenome_feature": feat,
                "n": int(len(m)), "positive_rate": float(y.mean()),
                "auroc": au, "auroc_sd": ausd, "auprc": ap, "auprc_sd": apsd,
                "dataset": f"03_datasets/{DATASET[task]}",
                "evaluation": f"mean over 3 chromosome-held-out folds, {common}",
            })

        reference_export["tasks"][task] = {
            "feature": feat,
            "orientation": "higher score = more disruptive; the percentile is increasing in it",
            "n_reference_variants": int(np.isfinite(raw).sum()),
            "n_distinct_scores": int(len(vals_ref)),
            "scores": [float(x) for x in vals_ref],
            "percentiles": [round(float(x), 8) for x in mid_ref],
        }
        print(f"[{task}] n={len(m)} AG present={int(observed.sum())}  "
              f"average AUROC={au_a:.4f} AUPRC={ap_a:.4f} | "
              f"ensemble {au_e:.4f}/{ap_e:.4f} | component {au_c:.4f}/{ap_c:.4f} | "
              f"grid dev {max_dev:.2e}", flush=True)

    for task in ("coding", "nonsnv"):
        summary_rows.append({
            "task": task, "offered": "no", "predictor": "MERGE + AlphaGenome average",
            "selected_alphagenome_feature": "", "n": "", "positive_rate": "",
            "auroc": "", "auroc_sd": "", "auprc": "", "auprc_sd": "",
            "dataset": "", "evaluation": "not offered: the AlphaGenome columns are near "
                                         "chance on this variant type",
        })

    pd.DataFrame(summary_rows).to_csv(outdir / "alphagenome_average_summary.csv", index=False)
    reference_export["sha256"] = sha256_of(reference_export["tasks"])
    (outdir / "alphagenome_reference_quantiles.json").write_text(
        json.dumps(reference_export, indent=1))
    print("wrote", outdir)


if __name__ == "__main__":
    run()
